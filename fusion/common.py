"""Shared helpers for the Fusion scripts: viewport setup and saving."""
import adsk.core, adsk.fusion

def setup_view():
    """Hide grid and ViewCube, use the shaded visual style (clean frames for rendering)."""
    app=adsk.core.Application.get(); ui=app.userInterface
    try:
        for li in ui.commandDefinitions.itemById('ViewLayoutGridOnCommand').controlDefinition.listItems:
            li.isSelected=False
    except Exception: pass
    try: ui.commandDefinitions.itemById('HideViewCubeCommand').execute()
    except Exception: pass
    app.activeViewport.visualStyle=adsk.core.VisualStyles.ShadedVisualStyle

def save_as(name, description='Generated by script'):
    """Save the active document into the root folder of the active Fusion project."""
    app=adsk.core.Application.get(); doc=app.activeDocument
    if doc.isSaved: return doc.save('updated by script')
    return doc.saveAs(name, app.data.activeProject.rootFolder, description, '')
